/**
 * Represents the keyboard input state for the game.
 * Each property corresponds to a key action and is stored as a boolean
 * to indicate whether the key is currently pressed.
 */
class Keyboard {

    /** @type {boolean} Whether the LEFT key is pressed */
    LEFT = false;

    /** @type {boolean} Whether the RIGHT key is pressed */
    RIGHT = false;

    /** @type {boolean} Whether the UP key (jump) is pressed */
    UP = false;

    /** @type {boolean} Whether the THROW key (throwing objects) is pressed */
    THROW = false;

    /** @type {boolean} Whether the PAUSE key is pressed */
    PAUSE = false;
}
